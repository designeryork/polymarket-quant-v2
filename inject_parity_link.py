#!/usr/bin/env python3
"""Add a link to the parity research page when publishing the dashboard.

Why this exists
---------------
The dashboard is generated by ``quant_engine.py`` and the running cloud job may
still be on an older revision that predates the parity-page link. Injecting the
link at publish time makes the page discoverable immediately, while the guard
(``href="parity.html"`` already present) makes it a no-op once the generator
starts emitting the link itself.

Usage:
    python inject_parity_link.py --input index.html --output index.html
"""
from __future__ import annotations

import argparse
from pathlib import Path

LINK = (
    '<a href="parity.html" target="_blank" rel="noopener" '
    'title="只读平价/事件篮子扫描">平价扫描</a>'
)
MARKER = '<a href="copy.html">跟单纸盘</a>'
FLOAT = (
    '<a href="parity.html" target="_blank" rel="noopener" '
    'style="position:fixed;right:16px;bottom:16px;z-index:9999;'
    'background:#162338;border:1px solid #2b3d56;color:#e5edf7;'
    'padding:8px 12px;border-radius:10px;font:600 12px system-ui,sans-serif;'
    'text-decoration:none">平价扫描 · 只读</a>'
)


def inject_html(text: str) -> str:
    if 'href="parity.html"' in text:
        return text
    if MARKER in text:
        return text.replace(MARKER, MARKER + LINK, 1)
    if "</body>" in text:
        return text.replace("</body>", FLOAT + "</body>", 1)
    return text


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True)
    parser.add_argument("--output", default="")
    args = parser.parse_args()
    src = Path(args.input)
    dst = Path(args.output) if args.output else src
    text = src.read_text(encoding="utf-8")
    updated = inject_html(text)
    dst.write_text(updated, encoding="utf-8")
    print(
        f"[inject_parity_link] {src} -> {dst} "
        f"({'updated' if updated != text else 'already present'})",
        flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
